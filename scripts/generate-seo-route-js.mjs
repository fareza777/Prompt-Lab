import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { HREFLANG_PAIRS, SEO_ROUTES, SITE } from "./seo-routes.mjs";

for (const [path, meta] of Object.entries(SEO_ROUTES)) {
  if (path !== "/" && !meta.routeKey) {
    throw new Error(`seo-routes.mjs: missing routeKey for ${path}`);
  }
}

function jsString(s) {
  return JSON.stringify(s);
}

const seoEntries = Object.entries(SEO_ROUTES)
  .map(([path, meta]) => {
    const fields = [
      `title: ${jsString(meta.title)}`,
      `description: ${jsString(meta.description)}`,
      `canonical: ${jsString(meta.canonical)}`,
      `h1: ${jsString(meta.h1)}`,
      `lang: ${jsString(meta.lang)}`,
      `ogType: ${jsString(meta.ogType || "website")}`,
    ];
    if (meta.keywords) fields.push(`keywords: ${jsString(meta.keywords)}`);
    if (meta.headline) fields.push(`headline: ${jsString(meta.headline)}`);
    if (meta.datePublished) fields.push(`datePublished: ${jsString(meta.datePublished)}`);
    if (meta.dateModified) fields.push(`dateModified: ${jsString(meta.dateModified)}`);
    return `    ${jsString(path)}: {\n      ${fields.join(",\n      ")},\n    }`;
  })
  .join(",\n");

const routeEntries = Object.entries(SEO_ROUTES)
  .filter(([path]) => path !== "/")
  .map(([path, meta]) => `    ${jsString(path)}: ${jsString(meta.routeKey)}`)
  .join(",\n");

const hreflangEntries = Object.entries(HREFLANG_PAIRS)
  .map(
    ([path, pair]) =>
      `    ${jsString(path)}: {\n      id: ${jsString(pair.id)},\n      en: ${jsString(pair.en)},\n    }`
  )
  .join(",\n");

const out = `/**
 * Early route + SEO bootstrap (sync in <head> after meta tags).
 * AUTO-GENERATED by scripts/generate-seo-route-js.mjs — do not edit by hand.
 */
(function () {
  var SITE = ${jsString(SITE)};

  var SEO = {
${seoEntries}
  };

  var ROUTES = {
    "/": "landing",
    "/app": "app",
${routeEntries}
  };

  function normalizePath(pathname) {
    return (pathname || "/").replace(/\\/+$/, "") || "/";
  }

  function setMetaContent(id, content) {
    var el = document.getElementById(id);
    if (el) el.setAttribute("content", content);
  }

  var HREFLANG_PAIRS = {
${hreflangEntries}
  };

  function applyHreflang(path, canonical) {
    var pair = HREFLANG_PAIRS[path];
    var enLink = document.getElementById("hreflang-en");
    var defaultLink = document.getElementById("hreflang-x-default");
    var idLink = document.getElementById("hreflang-id");

    if (pair) {
      if (!idLink) {
        idLink = document.createElement("link");
        idLink.id = "hreflang-id";
        idLink.rel = "alternate";
        idLink.hreflang = "id";
        var anchor = enLink || defaultLink;
        if (anchor && anchor.parentNode) anchor.parentNode.insertBefore(idLink, anchor.nextSibling);
        else document.head.appendChild(idLink);
      }
      if (enLink) enLink.href = pair.en;
      if (idLink) idLink.href = pair.id;
      if (defaultLink) defaultLink.href = pair.en;
      return;
    }

    if (idLink) idLink.remove();
    if (enLink) enLink.href = canonical;
    if (defaultLink) defaultLink.href = canonical;
  }

  function isoArticleTime(date) {
    return date + "T00:00:00.000Z";
  }

  function toggleArticleMeta(meta) {
    var published = document.getElementById("og-article-published");
    var modified = document.getElementById("og-article-modified");
    var isArticle = meta.ogType === "article" && meta.headline;

    if (isArticle) {
      if (!published) {
        published = document.createElement("meta");
        published.id = "og-article-published";
        published.setAttribute("property", "article:published_time");
        document.head.appendChild(published);
      }
      if (!modified) {
        modified = document.createElement("meta");
        modified.id = "og-article-modified";
        modified.setAttribute("property", "article:modified_time");
        document.head.appendChild(modified);
      }
      if (meta.datePublished) published.setAttribute("content", isoArticleTime(meta.datePublished));
      if (meta.dateModified || meta.datePublished) {
        modified.setAttribute("content", isoArticleTime(meta.dateModified || meta.datePublished));
      }
      if (meta.headline) setMetaContent("og-image-alt", meta.headline);
      return;
    }

    if (published) published.remove();
    if (modified) modified.remove();
    setMetaContent("og-image-alt", "PromptLab — AI Prompt Workspace");
  }

  function applySeoMeta(meta, path) {
    if (!meta) return;
    var title = document.getElementById("page-title");
    if (title) title.textContent = meta.title;
    setMetaContent("meta-description", meta.description);
    setMetaContent("og-title", meta.title);
    setMetaContent("og-description", meta.description);
    setMetaContent("og-url", meta.canonical);
    setMetaContent("twitter-title", meta.title);
    setMetaContent("twitter-description", meta.description);
    if (meta.keywords) setMetaContent("meta-keywords", meta.keywords);
    var ogType = document.getElementById("og-type");
    if (ogType && meta.ogType) ogType.setAttribute("content", meta.ogType);
    var canonical = document.getElementById("canonical-link");
    if (canonical) canonical.setAttribute("href", meta.canonical);
    if (meta.lang) document.documentElement.lang = meta.lang;
    applyHreflang(path, meta.canonical);
    toggleArticleMeta(meta);
  }

  function ensureRobotsNoindex() {
    if (document.querySelector('meta[name="robots"][data-app-noindex]')) return;
    var robots = document.createElement("meta");
    robots.name = "robots";
    robots.content = "noindex, nofollow";
    robots.setAttribute("data-app-noindex", "1");
    document.head.appendChild(robots);
  }

  function applyH1Visibility(activeH1) {
    document.querySelectorAll("[data-page-h1]").forEach(function (h1) {
      if (activeH1 && h1.getAttribute("data-page-h1") === activeH1) {
        h1.removeAttribute("aria-hidden");
      } else {
        h1.setAttribute("aria-hidden", "true");
      }
    });
  }

  var path = normalizePath(window.location.pathname);
  var standalone =
    window.matchMedia("(display-mode: standalone)").matches ||
    window.navigator.standalone === true;

  if (standalone && path === "/") {
    window.location.replace("/app" + window.location.search + window.location.hash);
    return;
  }

  var isApp = path === "/app" || path.startsWith("/app/");
  var routeKey = ROUTES[path] || "landing";
  var meta = SEO[path] || SEO["/"];

  if (isApp) {
    document.documentElement.classList.add("boot-app");
    document.documentElement.setAttribute("data-route", "app");
    ensureRobotsNoindex();
  } else {
    document.documentElement.setAttribute("data-route", routeKey);
    applySeoMeta(meta, path);
  }

  window.PromptLabRoute = {
    path: path,
    routeKey: routeKey,
    meta: meta,
    SEO: SEO,
    ROUTES: ROUTES,
    applyH1Visibility: function () {
      applyH1Visibility(isApp ? null : meta.h1);
    },
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      window.PromptLabRoute.applyH1Visibility();
    });
  } else {
    window.PromptLabRoute.applyH1Visibility();
  }
})();
`;

writeFileSync(join(process.cwd(), "public", "seo-route.js"), out, "utf8");
console.log("✓ public/seo-route.js generated");
